package ru.restofleet.agent.domain.port

/**
 * Данные, привязанные к учётке устройства (R-3, реш. 304): применённая тень с её версией, outbox и журнал
 * исполненных команд. [clear] стирает их при регистрации под другим `deviceId`, чтобы `desired` нового устройства не
 * отбрасывался как «старый», а записи прежнего не уходили в топики нового. Бросает, если стереть не удалось.
 */
fun interface DeviceDataReset {
    suspend fun clear()
}
